def translate_item(name):
    if name in ITEM:
        return ITEM[name]
    if name in WORDS:
        return WORDS[name]
    if name in ROOTS:
        return ROOTS[name]
    # Real database variants have numeric suffixes. Preserve these distinctions.
    match = re.fullmatch(r'(.+?)(\d+)', name)
    if match:
        return translate_item(match[1]) + '·' + match[2]
    # Parentheses and square brackets carry sex/class/quality/duration metadata.
    match = re.search(r'(\([^()]*\)|\[[^\[\]]*\])', name)
    if match:
        tag = match[0][1:-1]
        base = name[:match.start()] + name[match.end():]
        translated = TAGS.get(tag)
        if tag == 'M' and any(word in base for word in ('Stone', 'Drug', 'Aid', 'Torch', 'Knapsack', 'Box', 'Potion')):
            translated = '中'
        if translated is None and re.fullmatch(r'\d+[dhM]', tag):
            translated = re.sub(r'd$', '天', tag)
            translated = re.sub(r'h$', '小时', translated)
            translated = re.sub(r'M$', '个月', translated)
        if translated is None and re.fullmatch(r'\+?\d+', tag):
            translated = tag
        if translated is None:
            raise ValueError('unknown tag ' + tag)
        value = translate_item(base)
        return ('【' + translated + '】' + value) if match.start() == 0 else value + '（' + translated + '）'
    if name.startswith('Of'):
        return translate_item(name[2:])
    if 'Of' in name:
        left, right = name.split('Of', 1)
        return translate_item(right) + translate_item(left)
    if name in SUFFIX:
        return SUFFIX[name]
    for suffix in sorted(SUFFIX, key=len, reverse=True):
        if name.endswith(suffix) and len(name) > len(suffix):
            return translate_item(name[:-len(suffix)]) + SUFFIX[suffix]
    # Resolve compound roots explicitly; no English passthrough or generic labels.
    for prefix in sorted(ROOTS, key=len, reverse=True):
        if name.startswith(prefix) and len(name) > len(prefix):
            return ROOTS[prefix] + translate_item(name[len(prefix):])
    raise ValueError('unknown item root ' + name)


def translate_monster(name):
    if name in MONSTER:
        return MONSTER[name]
    if name.startswith('Ancient_'):
        return '远古' + translate_monster(name[8:])
    match = re.fullmatch(r'(.+?)(\d+)', name)
    if match:
        # Numbered Name entries share the translated GameName in play.
        return translate_monster(match[1]) + '·' + match[2]
    raise ValueError('unknown monster ' + name)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--input', type=Path, default=ROOT / '.ai/localization-data.json')
    parser.add_argument('--output', type=Path, default=ROOT / 'Localization/ItemsMonsters.zh-CN.json')
    args = parser.parse_args()
    data = json.loads(args.input.read_text(encoding='utf-8-sig'))
    output = {'Items': {}, 'Monsters': {}}
    unknown = {'Items': {}, 'Monsters': {}}
    # This database has Index 393, Name="00", GameName="". It has no semantic
    # name to translate. Keep the original key through the application's fallback.
    skipped = {'Monsters': ['00']}
    for group, names, translator in [
        ('Items', {row['Name'] for row in data['Items'] if row.get('Name')}, translate_item),
        ('Monsters', {row[field] for row in data['Monsters'] for field in ('Name', 'GameName') if row.get(field)}, translate_monster),
    ]:
        for name in sorted(names):
            if name in skipped.get(group, []):
                continue
            try:
                output[group][name] = translator(name)
            except ValueError as error:
                unknown[group][name] = str(error)
    print(json.dumps({'coverage': {key: len(value) for key, value in output.items()}, 'untranslated_placeholders': skipped, 'unknown': unknown}, ensure_ascii=False, indent=2))
    # Fail closed: do not write a partially translated dictionary by accident.
    if any(unknown.values()):
        raise SystemExit(1)
    assert all(re.search(r'[\u3400-\u9fff]', v) for group in output.values() for v in group.values())
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(output, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')


if __name__ == '__main__':
    main()
